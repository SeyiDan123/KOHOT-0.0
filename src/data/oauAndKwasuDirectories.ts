const buildFacultiesSummary = (departments: DepartmentItem[]) => {
  const map = new Map<string, string[]>();
  for (const dept of departments) {
    const list = map.get(dept.faculty) || [];
    if (!list.includes(dept.name)) {
      list.push(dept.name);
    }
    map.set(dept.faculty, list);
  }
  return Array.from(map.entries()).map(([facultyName, deptNames]) => ({
    facultyName,
    departments: deptNames,
  }));
};

